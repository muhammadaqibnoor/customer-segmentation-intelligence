import streamlit as st
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import plotly.express as px

st.set_page_config(
    page_title="Customer Intelligence Dashboard",
    page_icon="📊",
    layout="wide"
)

st.title("Customer Segmentation & Intelligence Dashboard")

st.markdown("""
Welcome to the Customer Intelligence Dashboard.
Explore customer segments, purchasing behavior,
and customer lifetime value.
""")

# Load customer data
@st.cache_data
def load_data():
    data = pd.read_csv("data/customer_rfm.csv", index_col=0)
    return data

rfm = load_data()

st.success("Customer data loaded successfully!")

# Sidebar Information
st.sidebar.title("Customer Intelligence")

st.sidebar.markdown("""
### Project Overview

**Project:** Customer Segmentation

**Method:** K-Means Clustering

**Features:**
- Recency
- Frequency
- Monetary Value

**Total Segments:** 4

**Dashboard:** Version 1.0
""")

st.sidebar.divider()

st.sidebar.info(
    "Explore customer behaviour and business performance using interactive analytics."
)

# Business KPI Calculations
total_customers = len(rfm)
total_revenue = rfm["Monetary"].sum()
average_clv = rfm["Monetary"].mean()
average_frequency = rfm["Frequency"].mean()

# Display KPI Cards
st.subheader("Business Performance Overview")

col1, col2, col3, col4 = st.columns(4)

col1.metric(
    "Total Customers",
    f"{total_customers:,}"
)

col2.metric(
    "Total Revenue",
    f"£{total_revenue:,.2f}"
)

col3.metric(
    "Average Customer Value",
    f"£{average_clv:,.2f}"
)

col4.metric(
    "Average Purchase Frequency",
    f"{average_frequency:.2f}"
)

# Customer Segment Distribution
st.subheader("Customer Segment Distribution")

segment_counts = rfm["Cluster_Name"].value_counts().reset_index()
segment_counts.columns = ["Customer Segment", "Customer Count"]

fig = px.pie(
    segment_counts,
    names="Customer Segment",
    values="Customer Count",
    title="Customer Distribution by Segment",
    hole=0.4
)

st.plotly_chart(fig, use_container_width=True)

# Revenue Contribution by Segment
st.subheader("Revenue Contribution by Customer Segment")

revenue_by_segment = (
    rfm.groupby("Cluster_Name")["Monetary"]
    .sum()
    .reset_index()
)

revenue_by_segment.columns = [
    "Customer Segment",
    "Total Revenue"
]

fig = px.bar(
    revenue_by_segment,
    x="Customer Segment",
    y="Total Revenue",
    color="Customer Segment",
    title="Revenue Generated by Each Customer Segment",
    text_auto=".2s"
)

st.plotly_chart(fig, use_container_width=True)

# Average Customer Value by Segment
st.subheader("Average Customer Value by Segment")

average_value = (
    rfm.groupby("Cluster_Name")["Monetary"]
    .mean()
    .reset_index()
)

average_value.columns = [
    "Customer Segment",
    "Average Customer Value"
]

fig = px.bar(
    average_value,
    x="Customer Segment",
    y="Average Customer Value",
    color="Customer Segment",
    title="Average Historical Customer Value",
    text_auto=".2s"
)

st.plotly_chart(fig, use_container_width=True)

# Average Purchase Frequency by Segment
st.subheader("Average Purchase Frequency by Segment")

frequency_by_segment = (
    rfm.groupby("Cluster_Name")["Frequency"]
    .mean()
    .reset_index()
)

frequency_by_segment.columns = [
    "Customer Segment",
    "Average Purchase Frequency"
]

fig = px.bar(
    frequency_by_segment,
    x="Customer Segment",
    y="Average Purchase Frequency",
    color="Customer Segment",
    title="Average Number of Purchases by Customer Segment",
    text_auto=".2f"
)

st.plotly_chart(fig, use_container_width=True)

# Average Recency by Segment
st.subheader("Average Recency by Segment")

recency_by_segment = (
    rfm.groupby("Cluster_Name")["Recency"]
    .mean()
    .reset_index()
)

recency_by_segment.columns = [
    "Customer Segment",
    "Average Recency (Days)"
]

fig = px.bar(
    recency_by_segment,
    x="Customer Segment",
    y="Average Recency (Days)",
    color="Customer Segment",
    title="Average Days Since Last Purchase",
    text_auto=".2f"
)

st.plotly_chart(fig, use_container_width=True)

# Interactive Customer Segment Filter
st.subheader("Explore Individual Customer Segments")

segments = ["All Segments"] + sorted(rfm["Cluster_Name"].unique().tolist())

selected_segment = st.selectbox(
    "Select Customer Segment",
    segments
)

if selected_segment == "All Segments":
    filtered_rfm = rfm
else:
    filtered_rfm = rfm[
        rfm["Cluster_Name"] == selected_segment
    ]

st.write(f"Customers in selected segment: {len(filtered_rfm):,}")

st.dataframe(filtered_rfm, use_container_width=True)
# Download Filtered Customer Data
csv = filtered_rfm.to_csv(index=True).encode("utf-8")

st.download_button(
    label="Download Customer Data (CSV)",
    data=csv,
    file_name="customer_segment_data.csv",
    mime="text/csv"
)

st.write("Dataset Preview")
st.dataframe(rfm.head())
